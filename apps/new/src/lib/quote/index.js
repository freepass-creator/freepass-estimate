// ============================================================================
//  견적 뼈대   —   신차·중고차가 «같이» 쓰는 자리
// ----------------------------------------------------------------------------
//  ★대표 2026-09-18 「신차 중고차 견적기의 뼈대는 동일하게 하고 싶은 거야.
//    우리 거는 우리 거 나름대로의 표준 견적 로직으로 갈 거고, 거의 웰릭스하고
//    비슷할 수밖에 없겠지만 더 효율적인 방법이 있는지를 볼 거고,
//    이것도 우리 거 뼈대에 웰릭스 계산 로직을 갖고 온 것처럼 만들어 놔야 돼」
//
//  뼈대가 하는 일 — 계산기가 바뀌어도 이건 안 바뀐다:
//    · 화면 상태를 규격에 맞는 «요청»으로 만든다   (build-request.js)
//    · 연속 입력을 묶는다 (150ms)
//    · 같은 요청은 두 번 묻지 않는다 (곳간 200칸)
//    · 늦게 온 답은 버린다 (순번)
//    · pending / ok / error 를 화면에 알린다
//    · 계산기가 준 결과가 규격에 맞는지 «받은 자리에서» 본다
//
//  계산기가 하는 일 — 이것만 갈아끼운다:
//    · 요청 → 결과.  그뿐이다.
//
//  계산기를 더할 때는 engines/ 에 파일 하나 만들고 아래 «계산기들» 에 줄 하나 더한다.
//  화면은 고치지 않는다.
// ============================================================================
import { reactive } from 'vue';
import { 요청만들기 } from './build-request.js';
import { 요청검사, 결과검사 } from './spec.js';
import * as 웰릭스 from './engines/welrix.js';

/* ── 꽂을 수 있는 계산기들 ─────────────────────────────────────────────────
   앞으로 여기에 붙는다:
     표준 — 우리 신차 표준 로직 (calc.js 를 다듬어서)
     중고 — 중고차 로직
   차.종류 로 고르거나, 계산기고르기() 로 손수 바꾼다. */
export const 계산기들 = {
  웰릭스,
};

let 쓰는계산기 = '웰릭스';

/** 어느 계산기로 낼지 바꾼다 — 같은 조건으로 계산기끼리 견줄 때도 쓴다 */
export function 계산기고르기(이름) {
  if (!계산기들[이름]) throw new Error(`그런 계산기가 없다: ${이름}`);
  쓰는계산기 = 이름;
  다시계산();
}
export function 지금계산기() { return 쓰는계산기; }

export const 견적상태 = reactive({
  상태: 'idle',        // idle | pending | ok | error
  결과: [],            // [{ 월대여료, 보증금, 선납금, 인수가, 총차량가, 수수료 } | null]
  오류: '',
  차량가: null,
  계산기: 쓰는계산기,
});

const 곳간 = new Map();
let 순번 = 0, 타이머 = null;

async function 보내기() {
  const 요청 = 요청만들기();
  if (!요청) { 비우기('idle'); return; }

  const 탈 = 요청검사(요청);
  if (탈) { 비우기('error', 탈); return; }

  const 계산기 = 계산기들[쓰는계산기];
  if (!계산기.다루는차.includes(요청.차.종류)) {
    비우기('error', `${계산기.이름} 계산기는 ${요청.차.종류}를 다루지 않습니다`);
    return;
  }

  const 글 = 쓰는계산기 + '|' + JSON.stringify(요청);
  const 캐시 = 곳간.get(글);
  if (캐시) {
    견적상태.결과 = 캐시.결과; 견적상태.차량가 = 캐시.차량가;
    견적상태.계산기 = 쓰는계산기; 견적상태.오류 = ''; 견적상태.상태 = 'ok';
    return;
  }

  const 내순번 = ++순번;
  견적상태.상태 = 'pending';
  견적상태.오류 = '';
  try {
    const 답 = await 계산기.계산(요청);
    if (내순번 !== 순번) return;                       // 그사이 조건이 또 바뀌었다

    const 탈2 = 결과검사(답?.결과, 요청.안들);
    if (탈2) { 비우기('error', 탈2); return; }

    if (곳간.size > 200) 곳간.delete(곳간.keys().next().value);
    곳간.set(글, 답);
    견적상태.결과 = 답.결과;
    견적상태.차량가 = 답.차량가 ?? null;
    견적상태.계산기 = 쓰는계산기;
    견적상태.상태 = 'ok';
  } catch (e) {
    if (내순번 !== 순번) return;
    /* ★다른 계산기로 «몰래 갈아타지» 않는다. 값이 달라지면 그게 더 나쁘다. */
    비우기('error', e?.message || '계산할 수 없습니다');
  }
}

function 비우기(상태, 오류 = '') {
  견적상태.상태 = 상태;
  견적상태.오류 = 오류;
  견적상태.결과 = [];
  견적상태.차량가 = null;
}

/** 조건이 바뀌면 부른다 — 연속 입력은 마지막 것만.
 *  ★조건을 바꾼 직후 debounce 150ms 동안 예전 결과가 'ok' 로 남으면
 *    그 찰나에 공유/발송했을 때 이전 금액 Snapshot 이 나갈 수 있다.
 *    그래서 변경 신호가 오는 즉시 pending 으로 잠그고, 새 결과가 온 뒤에만 ok 로 돌아간다. */
export function 다시계산() {
  clearTimeout(타이머);
  const 요청 = 요청만들기();
  if (!요청) { 비우기('idle'); return; }
  견적상태.상태 = 'pending';
  견적상태.오류 = '';
  타이머 = setTimeout(보내기, 150);
}
