import { QUOTE_REQUEST_CONTRACT } from './contracts.js';

// ============================================================================
//  견적 규격 — 뼈대와 계산기가 주고받는 «말»
// ----------------------------------------------------------------------------
//  ★대표 2026-09-18 「신차 중고차 견적기의 뼈대는 동일하게 하고 싶은 거야.
//    우리 거는 우리 거 나름대로의 표준 견적을 계산하기 위한 로직으로 갈 거고,
//    이것도 우리 거 뼈대에 웰릭스 계산 로직을 갖고 온 것처럼 만들어 놔야 돼」
//
//  그래서 «뼈대»와 «계산기»를 가른다.
//    뼈대   — 차를 고르고, 조건을 정하고, 결과를 보여준다. 하나뿐이다.
//    계산기 — 고른 차와 조건을 받아 월 대여료를 낸다. 여럿이다. 갈아끼운다.
//
//  화면은 «어느 계산기가 꽂혀 있는지 모른다». 그래야 계산기를 바꿔도 화면이 안 바뀐다.
// ----------------------------------------------------------------------------
//  ■ 요청 (뼈대 → 계산기) — 계산기와 무관한 «사실»만 담는다
//
//    {
//      차: {
//        종류:    '신차' | '중고차',
//        키:      계산기가 차를 알아보는 열쇠 (웰릭스는 model 문자열, 중고차는 재고 id)
//        차량가:  원   — 옵션·색 빼고 차값만
//        옵션가:  원   — 고른 옵션 합
//        색추가금: 원
//        할인:    원
//      },
//      조건: {
//        신용, 주행,          // '중신용' · '2만km'
//        정비, 대물, 추가운전자,
//        탁송비, 썬팅비, 블박비,   // ★원 단위 «금액»으로 준다. 어느 지역·어느 제품인지는 뼈대가 이미 풀었다
//        수수료율,            // % (7 = 7%)
//      },
//      안들: [ { 기간: 60, 보증금: 10, 선납: 0 }, ... ]   // % 단위
//    }
//
//  ■ 결과 (계산기 → 뼈대) — 안들과 «같은 차례·같은 길이»
//
//    [ { 월대여료, 보증금, 선납금, 인수가, 총차량가, 수수료 } ]
//    값을 못 내면 그 자리에 null 을 넣는다 (자리는 비우지 않는다).
//
//  ⚠ 비율은 규격 안에서 «퍼센트»로 다닌다 (10 = 10%).
//     웰릭스 API 는 비율(0.1)을 받으므로 «그 계산기 안에서» 나눈다. 뼈대는 몰라도 된다.
// ============================================================================

/** 요청이 규격에 맞나 — 계산기를 부르기 전에 뼈대가 스스로 본다 */
export function 요청검사(요청) {
  if (요청?.계약 && 요청.계약 !== QUOTE_REQUEST_CONTRACT) return `지원하지 않는 견적 요청 계약입니다: ${요청.계약}`;
  if (!요청?.차?.키) return '차를 아직 고르지 않았습니다';
  if (!Array.isArray(요청?.안들) || !요청.안들.length) return '기간이 정해지지 않았습니다';
  for (const a of 요청.안들) {
    if (!(a.기간 > 0)) return '기간이 올바르지 않습니다';
  }
  return null;
}

/** 결과 한 칸의 빈 모양 — 계산기가 값을 못 냈을 때 */
export const 빈칸 = null;

/** 결과가 규격에 맞나 — 계산기를 믿지 않고 뼈대가 받은 자리에서 본다 */
export function 결과검사(결과, 안들) {
  if (!Array.isArray(결과)) return '계산기가 목록을 주지 않았습니다';
  if (결과.length !== 안들.length) return `계산기가 ${안들.length}개를 줘야 하는데 ${결과.length}개를 줬습니다`;
  return null;
}
